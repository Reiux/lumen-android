fun getAvailablePresets(
    unlockedPrism: Boolean = false,
    unlockedMatrix: Boolean = false,
    unlockedSpooky: Boolean = false,
    unlockedXmas: Boolean = false,
    unlockedNewYr: Boolean = false,
    activeSeason: Season = Season.NONE
): List<ColorPreset> {
    val list = BasePresets.toMutableList()
    if (unlockedPrism) list.add(PrismPreset)
    if (unlockedMatrix) list.add(MatrixPreset)

    if (unlockedSpooky || activeSeason == Season.HALLOWEEN) list.add(SpookyPreset)
    if (unlockedXmas || activeSeason == Season.CHRISTMAS) list.add(XmasPreset)
    if (unlockedNewYr || activeSeason == Season.NEW_YEAR) list.add(NewYrPreset)

    return list
}

val AvailablePresets = BasePresets
